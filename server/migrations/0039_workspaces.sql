CREATE FUNCTION enforce_workspace_reference() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE condition TEXT; matched BOOLEAN; row_data JSONB=to_jsonb(NEW); parent_name TEXT=TG_ARGV[0]; source_keys TEXT[]=string_to_array(TG_ARGV[1],','); parent_keys TEXT[]=string_to_array(TG_ARGV[2],',');
BEGIN
 IF EXISTS(SELECT 1 FROM unnest(source_keys) k WHERE row_data->>k IS NULL) THEN RETURN NEW; END IF;
 SELECT string_agg(format('%I=($1->>%L)::%s',parent_keys[i],source_keys[i],format_type(a.atttypid,a.atttypmod)),' AND ')
 INTO condition FROM generate_subscripts(source_keys,1) i JOIN pg_attribute a ON a.attrelid=parent_name::regclass AND a.attname=parent_keys[i];
 EXECUTE format('SELECT EXISTS(SELECT 1 FROM %s WHERE workspace_id=$2 AND %s)',parent_name::regclass,condition)
 INTO matched USING row_data,NEW.workspace_id;
 IF NOT matched THEN RAISE EXCEPTION 'Resource must belong to the same workspace' USING ERRCODE='23503'; END IF;
 RETURN NEW;
END $$;
